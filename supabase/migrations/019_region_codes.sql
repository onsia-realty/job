-- MVP 범위: 서울 25구 + 경기 10개 시(23개 구 세분화 포함)
-- 나머지 지역은 v1.1 seed 파일로 추가 예정

CREATE TABLE IF NOT EXISTS region_codes (
  lawd_cd CHAR(5) PRIMARY KEY,
  sido VARCHAR(50) NOT NULL,
  sigungu VARCHAR(100) NOT NULL,
  full_name VARCHAR(200) NOT NULL,
  lat DOUBLE PRECISION,
  lng DOUBLE PRECISION,
  is_mvp BOOLEAN DEFAULT false,  -- MVP 대상 여부 (cron 동기화 필터용)
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_region_codes_sido ON region_codes(sido);
CREATE INDEX IF NOT EXISTS idx_region_codes_mvp ON region_codes(is_mvp) WHERE is_mvp = true;

ALTER TABLE region_codes ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Anyone can view region codes" ON region_codes
  FOR SELECT TO public
  USING (true);

